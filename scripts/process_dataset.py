import os
import csv
import json
import sys

# Ensure scripts folder is in the Python search path
sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from aura_model import AuraSkinModel

def generate_database_from_model():
    csv_path = r"d:\Kishmi\extracted\Facial Skin Condition Dataset.csv"
    base_dir = r"d:\Kishmi\extracted"
    output_js_path = r"d:\Kishmi\skin_database.js"
    
    print("==================================================")
    print("   DYNAMICAL AURA MODEL PREPROCESSOR RUNNING      ")
    print("==================================================")
    print(f"Reading CSV from {csv_path}...")
    
    # Initialize our Pillow-based Computer Vision Model
    model = AuraSkinModel()
    subjects = []
    
    # Read the CSV to match paths and check folders
    with open(csv_path, mode='r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            sub_id = int(row['id'])
            gender = row['gender']
            
            front_rel = f"{sub_id}/front.jpg"
            right_rel = f"{sub_id}/right-side.jpg"
            left_rel = f"{sub_id}/left-side.jpg"
            
            front_full = os.path.join(base_dir, f"{sub_id}", "front.jpg")
            
            # Check if file exists
            if not os.path.exists(front_full):
                print(f"[WARN] Subject {sub_id} front photo not found at: {front_full}. Skipping model run.")
                continue
                
            print(f"Running AURA CV Model on Subject {sub_id} front photo...")
            try:
                # 1. RUN PIXEL INTENSITY AND CHROMATIC COMPUTER VISION ANALYSIS LIVE!
                analysis = model.analyze_image(front_full)
                
                # Log computed metrics for transparency
                metrics = analysis["metrics"]
                print(f"  -> Lightness: {metrics['lightness']} | Shine: {metrics['shine_ratio']} | Acne Density: {metrics['acne_density']}")
                print(f"  -> Classed: {analysis['fitzpatrick']} | {analysis['undertone']} | {analysis['skinType']}")
                
                # 2. COMPILE CUSTOM REPORT BASED ON LIVE METRICS
                report = model.generate_aura_report(analysis, sub_id, gender)
                
                # 3. APPEND INTEGRATED RECORD
                subjects.append({
                    "id": sub_id,
                    "gender": gender,
                    "frontImage": f"extracted/{front_rel}",
                    "rightImage": f"extracted/{right_rel}",
                    "leftImage": f"extracted/{left_rel}",
                    "skinType": report["skinType"],
                    "undertone": report["undertone"],
                    "fitzpatrick": report["fitzpatrick"],
                    "story": report["story"],
                    "noticed": report["noticed"],
                    "ritual": report["ritual"],
                    "tips": report["tips"],
                    "dermWarning": report["dermWarning"],
                    "markers": report["markers"]
                })
            except Exception as e:
                print(f"[FAIL] Subject {sub_id} CV analysis failed: {e}")
                
    print("\n--------------------------------------------------")
    print(f"Successfully processed {len(subjects)} subjects using AURA CV Model.")
    
    # Write to JS file
    js_content = f"// This file is auto-generated by process_dataset.py. Do not edit directly.\n\nconst SKIN_DATABASE = {json.dumps(subjects, indent=2)};\n\nif (typeof module !== 'undefined' && module.exports) {{\n  module.exports = SKIN_DATABASE;\n}}\n"
    
    with open(output_js_path, mode='w', encoding='utf-8') as f:
        f.write(js_content)
        
    print(f"Successfully created skin database JS at {output_js_path}.")
    print("==================================================\n")

if __name__ == "__main__":
    generate_database_from_model()
